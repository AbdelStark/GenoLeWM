"""Tests for the measured eval-report generator."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from geno_lewm.errors import InputError
from geno_lewm.provenance import sha256_bytes
from tools.release.eval_report import main, parse_report_input, render_report


def test_release_tool_wrapper_delegates_to_installable_report_core() -> None:
    from geno_lewm import _evaluation_report
    from tools.release import eval_report

    assert eval_report.main is _evaluation_report.main
    assert eval_report.parse_report_input is _evaluation_report.parse_report_input
    assert eval_report.render_report is _evaluation_report.render_report


def test_render_report_includes_release_sections_and_measured_metrics() -> None:
    report_input = parse_report_input(_payload())

    rendered = render_report(report_input)

    assert rendered.startswith("# Evaluation Report\n")
    assert "Generated by: geno-lewm-eval-all" in rendered
    assert "## Results" in rendered
    assert "## Limitations" in rendered
    assert "## Negative Findings" in rendered
    assert "## Conclusions" in rendered
    assert (
        "| clinvar_coding_auroc | clinvar_coding | 0.73125 | auroc | carbon_zero_shot | 0.701 | 0.03025 |"
        in rendered
    )
    assert "planned targets are not reported as results" in rendered


def test_eval_report_main_writes_markdown(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    metrics_json = tmp_path / "metrics.json"
    output = tmp_path / "eval_report.md"
    metrics_json.write_text(json.dumps(_payload()), encoding="utf-8")

    rc = main(["--metrics-json", str(metrics_json), "--output", str(output)])
    captured = capsys.readouterr()

    assert rc == 0
    assert captured.out == f"wrote {output}\n"
    assert "Generated by: geno-lewm-eval-all" in output.read_text(encoding="utf-8")


