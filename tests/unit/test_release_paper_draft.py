def test_build_paper_draft_rejects_stale_eval_report(tmp_path: Path) -> None:
    paths = _write_complete_package(tmp_path)
    report_path = paths.model_dir / "eval_report.md"
    report_path.write_text(
        report_path.read_text(encoding="utf-8").replace(
            "The auroc metric value 0.73",
            "The result was measured",
        ),
        encoding="utf-8",
    )

    with pytest.raises(InputError, match="does not match render"):
        build_paper_draft(
            model_dir=paths.model_dir,
            dataset_dir=paths.dataset_dir,
            demo_dir=paths.demo_dir,
            output=tmp_path / "paper.md",
        )


