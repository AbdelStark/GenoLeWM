def test_build_paper_draft_requires_eval_config_artifact(tmp_path: Path) -> None:
    paths = _write_complete_package(tmp_path)
    metrics_path = paths.model_dir / "eval_metrics.json"
    payload = json.loads(metrics_path.read_text(encoding="utf-8"))
    del payload["artifacts"]["eval_config"]
    metrics_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")

    with pytest.raises(InputError, match="required keys"):
        build_paper_draft(
            model_dir=paths.model_dir,
            dataset_dir=paths.dataset_dir,
            demo_dir=paths.demo_dir,
            output=tmp_path / "paper.md",
        )
