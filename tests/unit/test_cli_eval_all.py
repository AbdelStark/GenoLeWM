def _payload(split: str, metric_name: str, value: float) -> dict[str, object]:
    return {
        "schema_version": "1.0.0",
        "generated_by": "geno-lewm-eval",
        "generated_at": (
            "2026-06-01T00:00:00Z" if split == "clinvar_coding" else "2026-06-01T00:01:00Z"
        ),
        "model_id": sha256_bytes(b"model"),
        "model_release": "geno-lewm-v0.1.0-r1",
        "dataset_snapshot": "geno-lewm-data-v0.1.0-r1",
        "commit": "abcdef1234567890",
        "hardware": "Apple M3 Max CPU",
        "metrics": [
            {
                "name": metric_name,
                "value": value,
                "split": split,
                "unit": "area",
                "higher_is_better": True,
                "ci_low": max(0.0, value - 0.05),
                "ci_high": min(1.0, value + 0.05),
                "n": 1200,
                "notes": f"held-out {split} variants",
            }
        ],
        "artifacts": {
            "checkpoint": "model/predictor.safetensors",
            "config": "model/train_config.yaml",
            "dataset_manifest": "dataset/dataset_manifest.json",
            "eval_config": "eval_config.effective.yaml",
            "efficiency_report": "model/efficiency_report.json",
            "scores": f"eval/{split}.scores.jsonl",
            "labels": f"eval/{split}.labels.jsonl",
        },
        "limitations": [
            "Single local hardware profile; no cross-platform timing claim is made.",
            "ClinVar label uncertainty is not resolved by this report.",
        ],
        "negative_findings": [
            "No prospective clinical utility is measured by this fixture report.",
        ],
        "conclusions": [
            (
                f"The {metric_name} metric value {value:.6g} on {split} was evaluated "
                "from measured score artifacts."
            ),
        ],
    }


def _v02_vep_payload() -> dict[str, object]:
    payload = _payload("clinvar_coding", "auroc", 0.73)
    metrics = [
        *_binary_metrics("clinvar_coding"),
        *_binary_metrics("clinvar_noncoding"),
        _baseline_metric("brca2", "spearman_rho", 0.61),
        _baseline_metric("traitgym_mendelian", "spearman_rho", 0.44),
    ]
    payload["metrics"] = metrics
    payload["generated_at"] = "2026-06-01T00:02:00Z"
    artifacts = payload["artifacts"]
    assert isinstance(artifacts, dict)
    artifacts["baseline_scores"] = "eval/carbon_zero_shot_scores.jsonl"
    payload["conclusions"] = [
        (
            f"The {metric['name']} metric value {metric['value']:.6g} on "
            f"{metric['split']} was evaluated from measured score artifacts "
            f"with delta {metric['delta_vs_baseline']:.6g} versus carbon_zero_shot."
        )
        for metric in metrics
    ]
    return payload


def _v02_rollout_payload() -> dict[str, object]:
    payload = _payload("rollout_phased_haplotypes", "cosine_similarity_mean", 0.91)
    metrics = [
        _rollout_metric("rollout_phased_haplotypes", "cosine_similarity_mean", 0.91),
        _rollout_metric("rollout_phased_haplotypes", "l2_distance_mean", 0.12),
        _rollout_metric("rollout_phased_haplotypes", "recall_at_k", 0.66),
        _rollout_metric("rollout_synthetic_edit_chains", "cosine_similarity_mean", 0.89),
        _rollout_metric("rollout_synthetic_edit_chains", "l2_distance_mean", 0.15),
        _rollout_metric("rollout_synthetic_edit_chains", "recall_at_k", 0.63),
    ]
    payload["metrics"] = metrics
    payload["generated_at"] = "2026-06-01T00:03:00Z"
    artifacts = payload["artifacts"]
    assert isinstance(artifacts, dict)
    artifacts.pop("scores")
    artifacts.pop("labels")
    artifacts["rollout_states"] = "eval/rollout_states.jsonl"
    artifacts["baseline_rollout_states"] = "eval/rollout_states.jsonl"
    artifacts["rollout_state_examples_report"] = "eval/rollout_state_examples_report.json"
    artifacts["rollout_state_rows_report"] = "eval/rollout_state_rows_report.json"
    payload["conclusions"] = [
        (
            f"The {metric['name']} metric value {metric['value']:.6g} on "
            f"{metric['split']} was evaluated from measured rollout state rows "
            f"with delta {metric['delta_vs_baseline']:.6g} versus {metric['baseline']}."
        )
        for metric in metrics
    ]
    return payload


def _binary_metrics(split: str) -> list[dict[str, object]]:
    return [
        _baseline_metric(split, "auroc", 0.73),
        _baseline_metric(split, "average_precision", 0.71),
        _baseline_metric(split, "balanced_accuracy", 0.69),
        _baseline_metric(split, "accuracy", 0.68),
    ]


def _baseline_metric(split: str, metric_name: str, value: float) -> dict[str, object]:
    variant_hash = sha256_bytes(f"{split}-{metric_name}-variant-keys".encode())
    metric = {
        "name": metric_name,
        "value": value,
        "split": split,
        "unit": "score",
        "higher_is_better": True,
        "baseline": "carbon_zero_shot",
        "baseline_value": value - 0.01,
        "delta_vs_baseline": 0.01,
        "ci_low": max(0.0, value - 0.05),
        "ci_high": min(1.0, value + 0.05),
        "n": 1200,
        "notes": f"held-out {split} variants",
        "evaluated_variant_keys_sha256": variant_hash,
        "baseline_evaluated_variant_keys_sha256": variant_hash,
    }
    return metric


def _rollout_metric(split: str, metric_name: str, value: float) -> dict[str, object]:
    state_hash = sha256_bytes(f"{split}-{metric_name}-rollout-state-ids".encode())
    return {
        "name": metric_name,
        "value": value,
        "split": split,
        "unit": "score",
        "higher_is_better": metric_name != "l2_distance_mean",
        "baseline": "source_state",
        "baseline_value": value - 0.01 if metric_name != "l2_distance_mean" else value + 0.01,
        "delta_vs_baseline": 0.01 if metric_name != "l2_distance_mean" else -0.01,
        "n": 1200,
        "notes": f"held-out {split} rollout states",
        "evaluated_variant_keys_sha256": state_hash,
        "baseline_evaluated_variant_keys_sha256": state_hash,
    }
