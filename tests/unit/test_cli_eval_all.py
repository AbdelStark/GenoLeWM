def test_eval_all_aggregates_metrics_and_renders_report(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    coding = tmp_path / "coding.metrics.json"
    noncoding = tmp_path / "noncoding.metrics.json"
    output_metrics = tmp_path / "aggregate.metrics.json"
    output_report = tmp_path / "eval_report.md"
    output_config = tmp_path / "eval_config.effective.yaml"
    coding.write_text(json.dumps(_payload("clinvar_coding", "auroc", 0.73)), encoding="utf-8")
    noncoding.write_text(
        json.dumps(_payload("clinvar_noncoding", "average_precision", 0.41)),
        encoding="utf-8",
    )

    rc = _dispatch.run_app(
        app,
        argv=[
            "--quiet",
            "--no-banner",
            "--metrics-json",
            str(coding),
            "--metrics-json",
            str(noncoding),
            "--output-metrics",
            str(output_metrics),
            "--output-report",
            str(output_report),
        ],
    )
    captured = capsys.readouterr()

    assert rc == 0
    summary = json.loads(captured.out)
    assert summary == {
        "eval_config": str(output_config),
        "eval_report": str(output_report),
        "inputs": 2,
        "metrics": 2,
        "metrics_json": str(output_metrics),
    }
    aggregate = load_report_input(output_metrics)
    assert aggregate.generated_by == "geno-lewm-eval-all"
    assert aggregate.generated_at == "2026-06-01T00:01:00Z"
    assert [metric.split for metric in aggregate.metrics] == [
        "clinvar_coding",
        "clinvar_noncoding",
    ]
    artifacts = dict(aggregate.artifacts)
    assert output_config.is_file()
    assert "run_id: eval" in output_config.read_text(encoding="utf-8")
    assert artifacts["eval_config"] == "eval_config.effective.yaml"
    assert artifacts["metrics_input_1"] == "coding.metrics.json"
    assert artifacts["metrics_input_2"] == "noncoding.metrics.json"
    assert "No prospective clinical utility is measured" in "\n".join(aggregate.negative_findings)
    assert "Aggregated 2 measured metric rows" in "\n".join(aggregate.conclusions)
    report = output_report.read_text(encoding="utf-8")
    assert "Generated by: geno-lewm-eval-all" in report
    assert "eval_config.effective.yaml" in report
    assert "clinvar_noncoding" in report


