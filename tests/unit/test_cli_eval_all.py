def test_eval_all_rejects_mismatched_release_identity(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    first = tmp_path / "first.metrics.json"
    second = tmp_path / "second.metrics.json"
    first.write_text(json.dumps(_payload("clinvar_coding", "auroc", 0.73)), encoding="utf-8")
    payload = _payload("clinvar_noncoding", "average_precision", 0.41)
    payload["model_id"] = sha256_bytes(b"other-model")
    second.write_text(json.dumps(payload), encoding="utf-8")

    rc = _dispatch.run_app(
        app,
        argv=[
            "--quiet",
            "--no-banner",
            "--metrics-json",
            str(first),
            "--metrics-json",
            str(second),
            "--output-metrics",
            str(tmp_path / "aggregate.metrics.json"),
            "--output-report",
            str(tmp_path / "eval_report.md"),
        ],
    )
    captured = capsys.readouterr()

    assert rc == 2
    assert "do not share release identity" in captured.err


def test_eval_all_rejects_metrics_inputs_outside_output_package(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    inputs_dir = tmp_path / "inputs"
    model_dir = tmp_path / "model"
    inputs_dir.mkdir()
    model_dir.mkdir()
    metrics = inputs_dir / "metrics.json"
    metrics.write_text(json.dumps(_payload("clinvar_coding", "auroc", 0.73)), encoding="utf-8")

    rc = _dispatch.run_app(
        app,
        argv=[
            "--quiet",
            "--no-banner",
            "--metrics-json",
            str(metrics),
            "--output-metrics",
            str(model_dir / "eval_metrics.json"),
            "--output-report",
            str(model_dir / "eval_report.md"),
        ],
    )
    captured = capsys.readouterr()

    assert rc == 2
    assert "must stay inside the aggregate metrics directory" in captured.err


def test_eval_all_rejects_absolute_artifact_references(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
) -> None:
    metrics = tmp_path / "metrics.json"
    payload = _payload("clinvar_coding", "auroc", 0.73)
    artifacts = payload["artifacts"]
    assert isinstance(artifacts, dict)
    artifacts["scores"] = str(tmp_path / "scores.jsonl")
    metrics.write_text(json.dumps(payload), encoding="utf-8")

    rc = _dispatch.run_app(
        app,
        argv=[
            "--quiet",
            "--no-banner",
            "--metrics-json",
            str(metrics),
            "--output-metrics",
            str(tmp_path / "eval_metrics.json"),
            "--output-report",
            str(tmp_path / "eval_report.md"),
        ],
    )
    captured = capsys.readouterr()

    assert rc == 2
    assert "artifact paths must be package-relative" in captured.err


def _payload(split: str, metric_name: str, value: float) -> dict[str, object]:
    return {
        "schema_version": "1.0.0",
        "generated_by": "geno-lewm-eval",
        "generated_at": (
            "2026-06-01T00:00:00Z" if split == "clinvar_coding" else "2026-06-01T00:01:00Z"
        ),
        "model_id": sha256_bytes(b"model"),
        "model_release": "geno-lewm-v0.1.0-r1",
        "dataset_snapshot": "geno-lewm-data-v0.1.0-r1",
        "commit": "abcdef1234567890",
        "hardware": "Apple M3 Max CPU",
        "metrics": [
            {
                "name": metric_name,
                "value": value,
                "split": split,
                "unit": "area",
                "higher_is_better": True,
                "ci_low": max(0.0, value - 0.05),
                "ci_high": min(1.0, value + 0.05),
                "n": 1200,
                "notes": f"held-out {split} variants",
            }
        ],
        "artifacts": {
            "checkpoint": "model/predictor.safetensors",
            "config": "model/train_config.yaml",
            "dataset_manifest": "dataset/dataset_manifest.json",
            "eval_config": "eval_config.effective.yaml",
            "efficiency_report": "model/efficiency_report.json",
            "scores": f"eval/{split}.scores.jsonl",
            "labels": f"eval/{split}.labels.jsonl",
        },
        "limitations": [
            "Single local hardware profile; no cross-platform timing claim is made.",
            "ClinVar label uncertainty is not resolved by this report.",
        ],
        "negative_findings": [
            "No prospective clinical utility is measured by this fixture report.",
        ],
        "conclusions": [
            (
                f"The {metric_name} metric value {value:.6g} on {split} was evaluated "
                "from measured score artifacts."
            ),
        ],
    }
