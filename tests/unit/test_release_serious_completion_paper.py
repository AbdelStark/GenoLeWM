def _planning_manifest_artifacts(planning_dir: Path) -> dict[str, object]:
    artifacts: dict[str, object] = {
        "model_manifest": {"path": "model/manifest.json", "sha256": MODEL_ID, "size_bytes": 1085},
        "predictor": {
            "path": "model/predictor.safetensors",
            "sha256": sha256_bytes(b"predictor"),
            "size_bytes": 122446936,
        },
        "action_encoder": {
            "path": "model/action_encoder.safetensors",
            "sha256": sha256_bytes(b"action_encoder"),
            "size_bytes": 8559712,
        },
    }
    for label, name in {
        "source_window": "source_window.fa",
        "target_window": "target_window.fa",
        "target_edits": "target_edits.json",
        "plan": "plan.json",
        "plan_stdout": "plan.stdout.json",
        "transcript": "planning-demo-transcript.md",
    }.items():
        path = planning_dir / name
        artifacts[label] = {
            "path": f"demo/{name}",
            "sha256": sha256_file(path),
            "size_bytes": path.stat().st_size,
        }
    return artifacts
