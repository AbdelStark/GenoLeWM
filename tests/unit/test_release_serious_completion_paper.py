def test_serious_completion_verifier_rejects_stale_generated_paper(tmp_path: Path) -> None:
    suite_dir, planning_dir = _write_serious_completion_inputs(tmp_path)
    output = tmp_path / "paper.serious.md"
    build_serious_completion_paper(
        suite_dir=suite_dir,
        planning_demo_dir=planning_dir,
        output=output,
        generated_at="2026-06-09T03:00:00Z",
    )
    output.write_text(
        output.read_text(encoding="utf-8").replace(
            "negative-results and systems",
            "improved-results and systems",
        ),
        encoding="utf-8",
    )

    report = verify_serious_completion_paper(
        SeriousCompletionPaperPaths(
            suite_dir=suite_dir,
            planning_demo_dir=planning_dir,
            paper_path=output,
        )
    )

    assert report.ok is False
    assert "serious_paper.negative_results" in _codes(report)
    assert "serious_paper.stale" in _codes(report)


def test_serious_completion_build_rejects_stale_planning_manifest_identity(
    tmp_path: Path,
) -> None:
    suite_dir, planning_dir = _write_serious_completion_inputs(tmp_path)
    (planning_dir / "source_window.fa").write_text(">13\nACGT\n", encoding="utf-8")

    with pytest.raises(InputError, match="artifact identity is stale"):
        build_serious_completion_paper(
            suite_dir=suite_dir,
            planning_demo_dir=planning_dir,
            output=tmp_path / "paper.serious.md",
        )


def _codes(report) -> set[str]:
    return {issue.code for issue in report.issues}


def _write_serious_completion_inputs(root: Path) -> tuple[Path, Path]:
    suite_dir = root / "suite"
    model_dir = suite_dir / "model"
    bench_dir = suite_dir / "bench"
    planning_dir = root / "planning-demo"
    model_dir.mkdir(parents=True)
    bench_dir.mkdir(parents=True)
    planning_dir.mkdir()

    metrics_payload = _eval_metrics_payload()
    metrics_path = model_dir / "eval_metrics.v02.json"
    metrics_path.write_text(
        json.dumps(metrics_payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    report = render_report(parse_report_input(metrics_payload))
    (model_dir / "eval_report.v02.md").write_text(report, encoding="utf-8")
    (model_dir / "efficiency_report.v02.json").write_text(
        json.dumps(_efficiency_payload(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (model_dir / "v0.2_benchmark_suite_report.json").write_text(
        json.dumps(_suite_report_payload(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (bench_dir / "rollout.ar_speed.json").write_text(
        json.dumps(_rollout_speed_payload(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (bench_dir / "rollout_speed_scope.json").write_text(
        json.dumps(
            _rollout_speed_scope_payload(bench_dir / "rollout.ar_speed.json"),
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    (model_dir / "v0.2_benchmark_readiness_report.json").write_text(
        json.dumps(_readiness_payload(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    _write_planning_artifacts(planning_dir)
    return suite_dir, planning_dir


